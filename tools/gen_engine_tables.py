#!/usr/bin/env python3
"""ETCH -- by Synth Centric.  Small bank-0 lookup tables for the audio
engine, replacing run-time multiplications inside the timer interrupt."""
import math
import sys

out = sys.argv[1] if len(sys.argv) > 1 else "src/audio/engine_tables.c"
L = []
A = L.append
A("/* AUTOGENERATED by tools/gen_engine_tables.py -- do not edit. */")
A("#include <stdint.h>")

# exponential envelope curve: curve[i] = 255 * exp(-i * 6 / 255)
curve = [int(round(255 * math.exp(-i * 6.0 / 255))) for i in range(256)]
curve[255] = 0
A("const uint8_t env_curve[256] = {" + ",".join(map(str, curve)) + "};")

# DEC 0..15 -> position increment (8.8) per 256 Hz tick.
# time to reach e^-6 (~ -52 dB): ticks = 256*256/inc
times = [0.06, 0.09, 0.13, 0.18, 0.25, 0.33, 0.43, 0.55, 0.7, 0.9, 1.15, 1.45, 1.85, 2.4, 3.2, 4.5]
incs = [max(1, int(round(256 * 256 / (t * 256)))) for t in times]
A("const uint16_t env_rate[16] = {" + ",".join(map(str, incs)) + "};")

# cutoff offset from envelope: envmod(0..15) * env(0..255) >> 7, env quantised to 32 levels
A("const uint8_t envmod_tbl[16 * 32] = {")
A(",".join(str((m * (e * 8 + 4)) >> 7) for m in range(16) for e in range(32)) + "};")

# accent sweep: accent(0..15) * aenv(0..255) >> 8, aenv in 16 levels
A("const uint8_t acc_tbl[16 * 16] = {")
A(",".join(str((a * (e * 16 + 8)) >> 8) for a in range(16) for e in range(16)) + "};")

# LFO amount: (lfo(-128..127, 32 levels) * depth) >> 4  (signed)
A("const int8_t lfo_amt[16 * 32] = {")
A(",".join(str(((l * 8 - 128 + 4) * d) >> 4) for d in range(16) for l in range(32)) + "};")
open(out, "w").write("\n".join(L) + "\n")
print("engine tables written")
