def glyph_pixels(ch, bold=True):
    """8x8 pixel matrix (values 0..3) for a glyph; bold = smear right."""
    rows = G[ch]
    px = [[0] * 8 for _ in range(8)]
    for y in range(7):
        for x in range(5):
            if rows[y][x] == '#':
                px[y][x + 1] = 3
                if bold:
                    px[y][x + 2] = 3
    return px


def tile_bytes(px):
    """8x8 matrix of colour indices -> 16 bytes 2bpp."""
    out = []
    for y in range(8):
        lo = hi = 0
        for x in range(8):
            c = px[y][x]
            lo |= (c & 1) << (7 - x)
            hi |= ((c >> 1) & 1) << (7 - x)
        out += [lo, hi]
    return out


def invert(px):
    return [[3 - c for c in row] for row in px]


def from_art(rows, palette=None):
    """rows: 8 strings of 8 chars using '.', '-', '+', '#' for shades 0..3."""
    m = {'.': 0, '-': 1, '+': 2, '#': 3}
    assert len(rows) == 8
    return [[m[c] for c in r] for r in rows]


