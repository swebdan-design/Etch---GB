    src_out = sys.argv[1] if len(sys.argv) > 1 else "src/ui/gfx_data.c"
    hdr_out = sys.argv[2] if len(sys.argv) > 2 else "include/gfx_tiles.h"
    font = []
    for code in range(32, 128):
        font += tile_bytes(glyph_pixels(chr(code)))
    inv = []
    for code in range(32, 96):
        inv += tile_bytes(invert(glyph_pixels(chr(code))))
    syms = []
    for _, p in SYM:
        syms += tile_bytes(p)
    ltiles, lmap = cut_tiles(logo_bitmap())
    # subtitle line rendered at 6 px pitch so all 25 characters fit on one row
    sub = text_bitmap("A GENERATIVE ACID MACHINE")
    stiles = []
    smap = []
    index = {t: i for i, t in enumerate(ltiles)}
    for tx in range(20):
        t = tuple(tile_bytes([[sub[y][tx * 8 + x] for x in range(8)] for y in range(8)]))
        if t not in index:
            index[t] = len(ltiles) + len(stiles)
            stiles.append(t)
        smap.append(160 + index[t])
    ltiles = ltiles + stiles
    assert len(ltiles) <= 64, len(ltiles)
    logo = [b for t in ltiles for b in t]
    lmap_flat = [160 + i for row in lmap for i in row]

