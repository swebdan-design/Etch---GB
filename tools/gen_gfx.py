# --- title logo -----------------------------------------------------------
# Block letters on a 6x8 grid, each block = 4x4 px -> each letter 24x32 px
# (3x4 tiles).  'Etched' look: every 4th scanline of the ink is cut to a
# mid shade, and a 1px shade-1 shadow falls to the lower right.
LOGO_LETTERS = {
    'E': ["######", "######", "##....", "#####.", "#####.", "##....", "######", "######"],
    'T': ["######", "######", "..##..", "..##..", "..##..", "..##..", "..##..", "..##.."],
    'C': [".#####", "######", "##....", "##....", "##....", "##....", "######", ".#####"],
    'H': ["##..##", "##..##", "##..##", "######", "######", "##..##", "##..##", "##..##"],
}


def logo_bitmap():
    word = "ETCH"
    gap = 8
    w = len(word) * 24 + (len(word) - 1) * gap
    h = 32
    W = ((w + 8 + 7) // 8) * 8
    H = 40
    ink = [[0] * W for _ in range(H)]
    for li, ch in enumerate(word):
        ox = 4 + li * (24 + gap)
        oy = 4
        rows = LOGO_LETTERS[ch]
        for by in range(8):
            for bx in range(6):
                if rows[by][bx] == '#':
                    for yy in range(4):
                        for xx in range(4):
                            ink[oy + by * 4 + yy][ox + bx * 4 + xx] = 1
    px = [[0] * W for _ in range(H)]
    for y in range(H):
        for x in range(W):
            if ink[y][x]:
                px[y][x] = 2 if (y % 4 == 2) else 3
            elif y > 0 and x > 0 and ink[y - 1][x - 1]:
                px[y][x] = 1
    return px


def cut_tiles(px):
    H = len(px)
    W = len(px[0])
    tiles = []
    tmap = []
    index = {}
    for ty in range(H // 8):
        row = []
        for tx in range(W // 8):
            t = [[px[ty * 8 + y][tx * 8 + x] for x in range(8)] for y in range(8)]
            b = tuple(tile_bytes(t))
            if b not in index:
                index[b] = len(tiles)
                tiles.append(b)
            row.append(index[b])
        tmap.append(row)
    return tiles, tmap


def text_bitmap(text, pitch=6, width_tiles=20):
    """Render text with the 5x7 font (not bold) at a tight pitch, centred."""
    W = width_tiles * 8
    px = [[0] * W for _ in range(8)]
    total = len(text) * pitch - 1
    ox = (W - total) // 2
    for i, ch in enumerate(text):
        rows = G[ch]
        for y in range(7):
            for x in range(5):
                if rows[y][x] == '#':
                    px[y][ox + i * pitch + x] = 3
    return px


def carr(name, data, per=16):
    s = "const uint8_t %s[%d] = {\n" % (name, len(data))
    for i in range(0, len(data), per):
        s += "  " + ",".join("0x%02X" % b for b in data[i:i + per]) + ",\n"
    return s + "};\n"


