/*
 * ETCH -- A Generative Acid Machine -- by Synth Centric
 * Acid bass voice on the CH3 wave channel.
 *
 * Signal model (per 256 Hz engine tick):
 *
 *   pitch (8.8 semitones) --slide/LFO--> period table + interpolation -> NR33/34
 *   filter env (16 bit, exp decay) + accent env + accent charge + LFO
 *        -> cutoff index 0..31, resonance index 0..7
 *   VCA level index 0..7 (0 = loudest) + drive mode 0..2
 *
 * Timbre is produced by selecting a pre-rendered 16-byte wavetable
 * [wave][res][cut] (tools/generate_waves.py) and passing it through a
 * 256-entry byte LUT [drive][amp] while copying into wave RAM.  Wave RAM is
 * only rewritten when one of those indices actually changes.
 *
 * Wave RAM update procedure (safe on DMG and CGB):
 *   NR30 = 0 (DAC off -> channel disabled; avoids the DMG wave-RAM
 *   corruption that occurs when wave RAM is written or the channel is
 *   retriggered while it is reading), write 16 bytes, NR30 = $80, retrigger.
 *   The retrigger restarts the waveform phase; this is audible as a soft
 *   "tick" during fast envelope sweeps and is part of the instrument's grain.
 */
#include <gbdk/platform.h>
#include "engine.h"

BANKREF_EXTERN(etch_wavetables)
BANKREF_EXTERN(etch_wavelut)
extern const uint8_t etch_wavetables[];
extern const uint8_t etch_wavelut[];

/* CH3 period register for notes C1..C6 (f = 65536 / (2048 - x)). */
static const uint16_t note_period[61] = {
    44, 157, 263, 363, 457, 547, 631, 711, 786, 856, 923, 986,
    1046, 1102, 1155, 1205, 1253, 1297, 1339, 1379, 1417, 1452, 1486, 1517,
    1547, 1575, 1602, 1627, 1650, 1673, 1694, 1714, 1732, 1750, 1767, 1783,
    1798, 1812, 1825, 1837, 1849, 1860, 1871, 1881, 1890, 1899, 1907, 1915,
    1923, 1930, 1936, 1943, 1949, 1954, 1959, 1964, 1969, 1974, 1978, 1982,
    1985
};
#define PITCH_MAX ((uint16_t)59 << 8)
uint16_t mul8x8(uint8_t a, uint8_t b);

/* Lookup tables generated by tools/gen_engine_tables.py (bank 0). */
extern const uint8_t  env_curve[256];
extern const uint16_t env_rate[16];
extern const uint8_t  envmod_tbl[16 * 32];
extern const uint8_t  acc_tbl[16 * 16];
extern const int8_t   lfo_amt[16 * 32];

/* LFO rate 0..15 -> phase increment (Hz * 256): 0.1 Hz .. 22 Hz */
static const uint16_t lfo_inc[16] = {
    26, 43, 64, 90, 128, 179, 256, 358, 512, 717, 1024, 1434, 2048, 2816, 4096, 5632
};

/* SLIDE TIME 0..15 -> RC glide: each tick the pitch moves by
 * (diff >> a) + (diff >> b) towards the target (b = 0: unused).
 * Time constants ~4 ms .. ~250 ms (exponential, like an analogue glide). */
static const uint8_t slide_a[16] = { 1, 1, 1, 2, 2, 2, 3, 3, 3, 4, 4, 4, 5, 5, 6, 6 };
static const uint8_t slide_b[16] = { 0, 2, 3, 0, 3, 4, 0, 4, 5, 0, 5, 6, 0, 6, 0, 7 };

volatile uint8_t synth_gate;
volatile uint8_t synth_dbg_cut, synth_dbg_res, synth_dbg_amp;
volatile uint8_t synth_reloads;

static uint16_t pitch;          /* 8.8 semitone, includes tune offset   */
static uint16_t pitch_target;
static uint8_t  slide_left;     /* 1 while gliding                       */
static uint8_t  sl_a, sl_b;
static uint16_t fenv_pos;       /* position on env_curve (8.8)          */
static uint16_t fenv_inc;       /* per-tick advance (from DEC)           */
static uint8_t  aenv;           /* accent envelope 0..255               */
static uint16_t last_pitch_out = 0xFFFF;
static uint8_t  acc_charge;     /* consecutive-accent build-up 0..120   */
static uint8_t  accented;
static uint8_t  amp;            /* VCA level index, 0 loudest           */
static uint8_t  amp_floor;
static uint8_t  amp_timer;
static uint16_t lfo_phase;
static int8_t   lfo_val;
static uint16_t lfo_rng = 0xACE1;
static uint8_t  cur_wave = 0xFF, cur_res, cur_cut, cur_amp, cur_drive;
static uint8_t  cur_hi;         /* last NR34 high bits                  */

static uint16_t note_to_pitch(uint8_t note)
{
    /* note 0 = C1 = table index 0; TUNE 12 = no transpose */
    int16_t n = (int16_t)note + (int16_t)proj.synth.tune - 12;
    if (n < 0) n = 0;
    if (n > 59) n = 59;
    return (uint16_t)n << 8;
}

static uint16_t pitch_to_period(uint16_t p)
{
    uint8_t n = (uint8_t)(p >> 8);
    uint8_t fr = (uint8_t)p;
    uint16_t base = note_period[n];
    uint8_t d = (uint8_t)(note_period[n + 1] - base);   /* <= 113 */
    if (!fr) return base;
    return base + (uint8_t)(mul8x8(d, fr) >> 8);
}

/* Copy wavetable [wave][res][cut] through LUT [drive][amp] into wave RAM
 * (hand-written assembly in wave_load.s; SDCC's C version cost ~10k cycles). */
extern uint8_t wl_w, wl_r, wl_c, wl_d, wl_a;
extern uint8_t wl_bank_w, wl_bank_l, wl_hi;
void wave_load_asm(void);
uint16_t mul8x8(uint8_t a, uint8_t b);

static void wave_load(void)
{
    wl_w = cur_wave; wl_r = cur_res; wl_c = cur_cut;
    wl_d = cur_drive; wl_a = cur_amp;
    wl_bank_w = BANK(etch_wavetables);
    wl_bank_l = BANK(etch_wavelut);
    wl_hi = cur_hi;
    wave_load_asm();
    synth_reloads++;
}

uint8_t synth_wave_peek(uint8_t wave, uint8_t res, uint8_t cut, uint8_t *out16)
{
    uint8_t i;
    uint8_t save = CURRENT_BANK;
    const uint8_t *src = etch_wavetables
        + ((uint16_t)((wave << 3) | res) << 9) + ((uint16_t)cut << 4);
    SWITCH_ROM(BANK(etch_wavetables));
    for (i = 0; i < 16; i++) out16[i] = src[i];
    SWITCH_ROM(save);
    return 16;
}

void synth_init(void)
{
    NR30_REG = 0x00;
    NR32_REG = 0x00;
    synth_gate = 0;
    cur_wave = 0xFF;
    acc_charge = 0;
}

static void write_pitch(void)
{
    uint16_t p = pitch;
    uint16_t per;
    if (proj.synth.lfo_dest == LFO_PITCH && proj.synth.lfo_depth) {
        int8_t off = lfo_amt[((uint8_t)proj.synth.lfo_depth << 5) | ((uint8_t)(lfo_val + 128) >> 3)];
        int16_t o = (int16_t)off << 1;           /* up to ~1 semitone */
        if (o < 0 && (uint16_t)(-o) > p) p = 0;
        else p += o;
        if (p > PITCH_MAX) p = PITCH_MAX;
    }
    if (p == last_pitch_out) return;             /* nothing to do */
    last_pitch_out = p;
    per = pitch_to_period(p);
    NR33_REG = (uint8_t)per;
    cur_hi = (uint8_t)(per >> 8) & 0x07;
    NR34_REG = cur_hi;               /* no trigger: phase continues */
}

static void start_envelopes(uint8_t accent)
{
    uint8_t d = proj.synth.decay & 15;
    if (accent && d > 6) d = 6;              /* accented notes snap shut */
    fenv_pos = 0;
    fenv_inc = env_rate[d];
    accented = accent;
    if (accent) {
        aenv = 255;
        acc_charge += 40;
        if (acc_charge > 120) acc_charge = 120;
        amp = 0;
    } else {
        aenv = 0;
        amp = proj.synth.accent >> 2;   /* ACC widens the loudness gap */
    }
    amp_floor = amp + 3;
    if (amp_floor > 5) amp_floor = 5;
    amp_timer = 0;
}

void synth_note_on(uint8_t note, uint8_t accent)
{
    pitch = pitch_target = note_to_pitch(note);
    slide_left = 0;
    start_envelopes(accent);
    synth_gate = 1;
    last_pitch_out = 0xFFFF;
    write_pitch();
    cur_wave = 0xFF;                 /* force wave reload + retrigger */
}

void synth_glide(uint8_t note, uint8_t accent)
{
    if (synth_gate != 1) { synth_note_on(note, accent); return; }
    pitch_target = note_to_pitch(note);
    sl_a = slide_a[proj.synth.slide & 15];
    sl_b = slide_b[proj.synth.slide & 15];
    slide_left = (pitch_target != pitch);
    if (accent) {                    /* accent on a slid note: no env reset, */
        aenv = 255;                  /* but the accent sweep and loudness    */
        accented = 1;
        amp = 0;
        acc_charge += 40;
        if (acc_charge > 120) acc_charge = 120;
    }
}

void synth_gate_off(void)
{
    if (synth_gate == 1) synth_gate = 2;
}

void synth_kill(void)
{
    synth_gate = 0;
    NR32_REG = 0x00;
    NR30_REG = 0x00;
    cur_wave = 0xFF;
    last_pitch_out = 0xFFFF;
}

void synth_step_tick(void)
{
    acc_charge -= acc_charge >> 3;
}

static void lfo_tick(void)
{
    uint16_t old = lfo_phase;
    uint8_t p;
    lfo_phase += lfo_inc[proj.synth.lfo_rate & 15];
    p = (uint8_t)(lfo_phase >> 8);
    switch (proj.synth.lfo_shape) {
    case LFO_TRI:
        lfo_val = (int8_t)((p < 128 ? (p << 1) : ((255 - p) << 1)) - 128);
        break;
    case LFO_SQR:
        lfo_val = p < 128 ? 120 : -120;
        break;
    case LFO_SAW:
        lfo_val = (int8_t)(127 - p);
        break;
    default:
        if (lfo_phase < old) {
            lfo_rng ^= lfo_rng << 7;
            lfo_rng ^= lfo_rng >> 9;
            lfo_rng ^= lfo_rng << 8;
            lfo_val = (int8_t)(uint8_t)lfo_rng;
        }
        break;
    }
}

void synth_tick(void)
{
    uint8_t e, cut, res, wave, drive;
    int8_t c, r;

    lfo_tick();
    if (!synth_gate) return;

    /* --- release ----------------------------------------------------- */
    if (synth_gate == 2) {
        amp += 2;
        if (amp > 7) {
            synth_kill();
            return;
        }
    }

    /* --- pitch slide -------------------------------------------------- */
    if (slide_left) {
        uint16_t d, st;
        if (pitch_target > pitch) {
            d = pitch_target - pitch;
            st = (d >> sl_a) + (sl_b ? (d >> sl_b) : 0) + 1;
            if (st >= d) { pitch = pitch_target; slide_left = 0; }
            else pitch += st;
        } else {
            d = pitch - pitch_target;
            st = (d >> sl_a) + (sl_b ? (d >> sl_b) : 0) + 1;
            if (st >= d) { pitch = pitch_target; slide_left = 0; }
            else pitch -= st;
        }
    }
    write_pitch();

    /* --- filter envelope: walk an exponential curve ------------------- */
    if (fenv_pos < 0xFF00) {
        fenv_pos += fenv_inc;
        if (fenv_pos > 0xFF00 || fenv_pos < fenv_inc) fenv_pos = 0xFF00;
    }
    e = env_curve[(uint8_t)(fenv_pos >> 8)];
    if (aenv) aenv -= (aenv >> 4) + 1;

    /* --- VCA decay ---------------------------------------------------- */
    if (synth_gate == 1 && amp < amp_floor) {
        if (++amp_timer >= (uint8_t)(10 + (proj.synth.decay << 2))) {
            amp_timer = 0;
            amp++;
        }
    }

    /* --- cutoff / resonance ------------------------------------------- */
    c = (int8_t)(proj.synth.cutoff
        + envmod_tbl[((uint8_t)proj.synth.envmod << 5) | (e >> 3)]
        + acc_tbl[((uint8_t)proj.synth.accent << 4) | (aenv >> 4)]
        + (acc_charge >> 4));
    r = (int8_t)proj.synth.res;
    if (proj.synth.lfo_depth && proj.synth.lfo_dest >= LFO_CUT) {
        int8_t amt = lfo_amt[((uint8_t)proj.synth.lfo_depth << 5) | ((uint8_t)(lfo_val + 128) >> 3)];
        if (proj.synth.lfo_dest == LFO_CUT) c += amt >> 3;
        else r += amt >> 4;
    }
    if (c < 0) c = 0;
    if (c > 31) c = 31;
    if (r < 0) r = 0;
    if (r > 7) r = 7;
    cut = (uint8_t)c;
    res = (uint8_t)r;
    wave = proj.synth.wave & 3;
    drive = proj.synth.drive;
    if (drive > 2) drive = 2;

    if (wave != cur_wave || cut != cur_cut || res != cur_res ||
        amp != cur_amp || drive != cur_drive) {
        cur_wave = wave;
        cur_cut = cut;
        cur_res = res;
        cur_amp = amp;
        cur_drive = drive;
        wave_load();
    }
    synth_dbg_cut = cut;
    synth_dbg_res = res;
    synth_dbg_amp = amp;
}
